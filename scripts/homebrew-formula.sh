#!/usr/bin/env bash
# Render the Homebrew formula for a release from its SHA256SUMS file.
# Usage: scripts/homebrew-formula.sh v0.1.0 dist/SHA256SUMS > Formula/openprofiler.rb
set -euo pipefail

tag=${1:?usage: $0 <tag> <SHA256SUMS>}
sums=${2:?usage: $0 <tag> <SHA256SUMS>}
version=${tag#v}
base="https://github.com/matusso/openprofiler/releases/download/$tag"

sha() {
  local file="openprofiler-$tag-$1.tar.gz" sum
  sum=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [[ -n "$sum" ]] || { echo "missing checksum for $file" >&2; exit 1; }
  echo "$sum"
}

cat <<RUBY
# Generated by scripts/homebrew-formula.sh; do not edit by hand.
class Openprofiler < Formula
  desc "Open-source JVM profiler: CPU, allocations, heap dumps, JFR and live attach"
  homepage "https://github.com/matusso/openprofiler"
  version "$version"
  license all_of: ["Apache-2.0", "MPL-2.0"]

  on_macos do
    on_arm do
      url "$base/openprofiler-$tag-darwin-arm64.tar.gz"
      sha256 "$(sha darwin-arm64)"
    end
    on_intel do
      url "$base/openprofiler-$tag-darwin-amd64.tar.gz"
      sha256 "$(sha darwin-amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$base/openprofiler-$tag-linux-arm64.tar.gz"
      sha256 "$(sha linux-arm64)"
    end
    on_intel do
      url "$base/openprofiler-$tag-linux-amd64.tar.gz"
      sha256 "$(sha linux-amd64)"
    end
  end

  def install
    # The CLI finds the agent, web UI and remote bundle next to its resolved path.
    libexec.install Dir["*"]
    bin.install_symlink libexec/"openprofiler"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/openprofiler --version")
  end
end
RUBY
