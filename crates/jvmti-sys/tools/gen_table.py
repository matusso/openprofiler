#!/usr/bin/env python3
"""Generates src/table.rs (the jvmtiInterface_1_ function table) from a JDK jvmti.h.

Run once against a JDK 21+ header and commit the output; the build does not need libclang.
Usage: python3 tools/gen_table.py $JAVA_HOME/include/jvmti.h > src/table.rs
"""
import re, sys

src = open(sys.argv[1]).read()
body = src[src.index("typedef struct jvmtiInterface_1_ {"):src.index("} jvmtiInterface_1;")]
body = body.split("{", 1)[1]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)

def rtype(t):
    t = t.strip()
    is_const = t.startswith("const ")
    t = t.replace("const ", "")
    ptr = t.count("*")
    base = t.replace("*", "").strip()
    m = {
        "void": "c_void", "char": "c_char", "unsigned char": "u8", "jint": "jint", "jlong": "jlong",
        "jboolean": "jboolean", "jfloat": "jfloat", "jdouble": "jdouble", "jchar": "jchar",
        "jobject": "jobject", "jclass": "jclass", "jthread": "jthread", "jthreadGroup": "jthreadGroup",
        "jmethodID": "jmethodID", "jfieldID": "jfieldID", "jlocation": "jlocation",
        "jvmtiEnv": "jvmtiEnv", "JNIEnv": "JNIEnv", "jniNativeInterface": "JNINativeInterface_",
        "jvalue": "jvalue", "jrawMonitorID": "jrawMonitorID", "jweak": "jweak",
        "unsigned int": "u32",
    }
    if base in m:
        r = m[base]
    elif base.startswith("jvmti"):
        r = base
    else:
        raise SystemExit(f"unknown type {t!r}")
    for i in range(ptr):
        # `const T*` points to const data: the innermost pointer is *const.
        r = f"*const {r}" if (is_const and i == 0) else f"*mut {r}"
    return r

out = []
for decl in body.split(";"):
    decl = " ".join(decl.split())
    if not decl:
        continue
    m = re.match(r"void \*(\w+)$", decl)
    if m:
        out.append(f"    pub {m.group(1)}: *mut c_void,")
        continue
    m = re.match(r"(.+?) \(JNICALL \*(\w+)\) \((.*)\)$", decl)
    if not m:
        raise SystemExit(f"cannot parse: {decl}")
    ret, name, params = m.groups()
    args = []
    variadic = False
    for p in [p.strip() for p in params.split(",")]:
        if p == "...":
            variadic = True
            continue
        pm = re.match(r"(.*?)(\w+)$", p)
        ty, pname = pm.groups()
        if pname in ("type", "ref", "loop", "move", "fn", "impl", "self"):
            pname = "r#" + pname
        args.append(f"{pname}: {rtype(ty)}")
    if variadic:
        args.append("...")
    ret_r = rtype(ret)
    ret_s = "" if ret_r == "c_void" else f" -> {ret_r}"
    out.append(f"    pub {name}: Option<unsafe extern \"C\" fn({', '.join(args)}){ret_s}>,")

print("// @generated by tools/gen_table.py from the JDK's jvmti.h. Do not edit by hand.")
print("#![allow(non_snake_case, clippy::type_complexity)]\n")
print("use crate::*;")
print("use std::ffi::{c_char, c_void};\n")
print("#[repr(C)]")
print("pub struct jvmtiInterface_1_ {")
print("\n".join(out))
print("}")
